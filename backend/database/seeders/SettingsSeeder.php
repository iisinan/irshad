            ['key' => 'zakat_exchange_rate', 'value' => '1600'],
            ['key' => 'zakat_gold_price_override', 'value' => ''],
        ];

        foreach ($settings as $setting) {
            Setting::updateOrCreate(
                ['key' => $setting['key']],
                ['value' => $setting['value']]
            );
        }
    }
}
